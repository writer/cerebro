// Package openapitsgen generates TypeScript type definitions from a Cerebro
// OpenAPI specification. This bridges the cross-repo type gap between cerebro
// (Go) and cerebro-web (TypeScript) by producing types from the single source
// of truth rather than maintaining them by hand.
package openapitsgen

import (
	"fmt"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// Schema mirrors the subset of OpenAPI 3.x schema objects used in the Cerebro
// API spec. Only fields that influence TypeScript type emission are included.
type Schema struct {
	Type                 string             `yaml:"type" json:"type"`
	Format               string             `yaml:"format" json:"format"`
	Description          string             `yaml:"description" json:"description"`
	Enum                 []string           `yaml:"enum" json:"enum"`
	Properties           map[string]*Schema `yaml:"properties" json:"properties"`
	Items                *Schema            `yaml:"items" json:"items"`
	AdditionalProperties any                `yaml:"additionalProperties" json:"additionalProperties"`
	Required             []string           `yaml:"required" json:"required"`
	OneOf                []*Schema          `yaml:"oneOf" json:"oneOf"`
	AnyOf                []*Schema          `yaml:"anyOf" json:"anyOf"`
	AllOf                []*Schema          `yaml:"allOf" json:"allOf"`
	Ref                  string             `yaml:"$ref" json:"$ref"`
}

// Spec mirrors the top-level OpenAPI document enough to extract component
// schemas.
type Spec struct {
	Components struct {
		Schemas map[string]*Schema `yaml:"schemas" json:"schemas"`
	} `yaml:"components" json:"components"`
}

// GenerateResult holds the generated TypeScript output and metadata.
type GenerateResult struct {
	TypeScript string
	TypeCount  int
}

// Generate produces TypeScript type definitions from an OpenAPI spec payload.
func Generate(specPayload []byte) (GenerateResult, error) {
	var spec Spec
	if err := yaml.Unmarshal(specPayload, &spec); err != nil {
		return GenerateResult{}, fmt.Errorf("parse OpenAPI spec: %w", err)
	}
	schemas := spec.Components.Schemas
	if len(schemas) == 0 {
		return GenerateResult{}, fmt.Errorf("no component schemas found in OpenAPI spec")
	}
	names := sortedKeys(schemas)
	var b strings.Builder
	b.WriteString("// Code generated by tools/openapitsgen from api/openapi.yaml. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// To regenerate, run: make openapi-ts-generate\n\n")
	for _, name := range names {
		schema := schemas[name]
		if schema == nil {
			continue
		}
		emitSchema(&b, name, schema, schemas)
	}
	return GenerateResult{TypeScript: b.String(), TypeCount: len(names)}, nil
}

func emitSchema(b *strings.Builder, name string, schema *Schema, all map[string]*Schema) {
	if len(schema.Enum) > 0 {
		emitEnum(b, name, schema)
		return
	}
	if schema.Type == "object" || len(schema.Properties) > 0 || len(schema.AllOf) > 0 {
		emitObjectType(b, name, schema, all)
		return
	}
	// Simple type alias.
	fmt.Fprintf(b, "export type %s = %s;\n\n", name, tsType(schema, all))
}

func emitEnum(b *strings.Builder, name string, schema *Schema) {
	if schema.Description != "" {
		fmt.Fprintf(b, "/** %s */\n", singleLineComment(schema.Description))
	}
	fmt.Fprintf(b, "export type %s =\n", name)
	for i, value := range schema.Enum {
		sep := ""
		if i == len(schema.Enum)-1 {
			sep = ";"
		}
		fmt.Fprintf(b, "  | %q%s\n", value, sep)
	}
	b.WriteString("\n")
}

func emitObjectType(b *strings.Builder, name string, schema *Schema, all map[string]*Schema) {
	if schema.Description != "" {
		fmt.Fprintf(b, "/** %s */\n", singleLineComment(schema.Description))
	}

	// Collect properties from the schema and allOf.
	properties := mergeProperties(schema, all)
	requiredSet := requiredFields(schema, all)

	if len(properties) == 0 && schema.AdditionalProperties != nil {
		fmt.Fprintf(b, "export type %s = Record<string, %s>;\n\n", name, additionalPropertiesType(schema.AdditionalProperties, all))
		return
	}
	if len(properties) == 0 {
		fmt.Fprintf(b, "export type %s = Record<string, unknown>;\n\n", name)
		return
	}

	fmt.Fprintf(b, "export type %s = {\n", name)
	propNames := sortedKeys(properties)
	for _, propName := range propNames {
		propSchema := properties[propName]
		optional := "?"
		if requiredSet[propName] {
			optional = ""
		}
		propType := tsType(propSchema, all)
		fmt.Fprintf(b, "  %s%s: %s;\n", propName, optional, propType)
	}
	if schema.AdditionalProperties != nil {
		addType := additionalPropertiesType(schema.AdditionalProperties, all)
		fmt.Fprintf(b, "  [key: string]: %s;\n", addType)
	}
	b.WriteString("};\n\n")
}

func mergeProperties(schema *Schema, all map[string]*Schema) map[string]*Schema {
	properties := map[string]*Schema{}
	for _, sub := range schema.AllOf {
		resolved := resolveRef(sub, all)
		if resolved == nil {
			continue
		}
		for key, value := range mergeProperties(resolved, all) {
			properties[key] = value
		}
	}
	for key, value := range schema.Properties {
		properties[key] = value
	}
	return properties
}

func requiredFields(schema *Schema, all map[string]*Schema) map[string]bool {
	result := map[string]bool{}
	for _, name := range schema.Required {
		result[name] = true
	}
	for _, sub := range schema.AllOf {
		resolved := resolveRef(sub, all)
		if resolved == nil {
			continue
		}
		for name, ok := range requiredFields(resolved, all) {
			if ok {
				result[name] = true
			}
		}
	}
	return result
}

func tsType(schema *Schema, all map[string]*Schema) string {
	if schema == nil {
		return "unknown"
	}
	if schema.Ref != "" {
		return refName(schema.Ref)
	}
	if len(schema.OneOf) > 0 {
		return unionType(schema.OneOf, all)
	}
	if len(schema.AnyOf) > 0 {
		return unionType(schema.AnyOf, all)
	}
	if len(schema.Enum) > 0 {
		parts := make([]string, len(schema.Enum))
		for i, value := range schema.Enum {
			parts[i] = fmt.Sprintf("%q", value)
		}
		return strings.Join(parts, " | ")
	}
	switch schema.Type {
	case "string":
		if schema.Format == "date-time" {
			return "string"
		}
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		itemType := tsType(schema.Items, all)
		return itemType + "[]"
	case "object":
		if schema.AdditionalProperties != nil {
			return "Record<string, " + additionalPropertiesType(schema.AdditionalProperties, all) + ">"
		}
		if len(schema.Properties) > 0 {
			return inlineObject(schema, all)
		}
		return "Record<string, unknown>"
	default:
		return "unknown"
	}
}

func inlineObject(schema *Schema, all map[string]*Schema) string {
	var b strings.Builder
	b.WriteString("{ ")
	propNames := sortedKeys(schema.Properties)
	for i, propName := range propNames {
		propSchema := schema.Properties[propName]
		propType := tsType(propSchema, all)
		fmt.Fprintf(&b, "%s?: %s", propName, propType)
		if i < len(propNames)-1 {
			b.WriteString("; ")
		}
	}
	b.WriteString(" }")
	return b.String()
}

func additionalPropertiesType(additionalProperties any, all map[string]*Schema) string {
	switch typed := additionalProperties.(type) {
	case bool:
		return "unknown"
	case *Schema:
		return tsType(typed, all)
	case map[string]any:
		// YAML deserialized as map, try to extract type.
		if typeValue, ok := typed["type"].(string); ok {
			return primitiveTS(typeValue)
		}
		return "unknown"
	default:
		return "unknown"
	}
}

func unionType(schemas []*Schema, all map[string]*Schema) string {
	parts := make([]string, len(schemas))
	for i, schema := range schemas {
		parts[i] = tsType(schema, all)
	}
	return strings.Join(parts, " | ")
}

func resolveRef(schema *Schema, all map[string]*Schema) *Schema {
	if schema == nil {
		return nil
	}
	if schema.Ref != "" {
		name := refName(schema.Ref)
		if resolved, ok := all[name]; ok {
			return resolved
		}
		return nil
	}
	return schema
}

func refName(ref string) string {
	parts := strings.Split(ref, "/")
	return parts[len(parts)-1]
}

func primitiveTS(goType string) string {
	switch goType {
	case "string":
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	default:
		return "unknown"
	}
}

func singleLineComment(description string) string {
	description = strings.ReplaceAll(description, "\n", " ")
	description = strings.TrimSpace(description)
	if len(description) > 120 {
		description = description[:117] + "..."
	}
	return description
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

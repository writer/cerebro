package archtests

import (
	"os"
	"strings"
)

const sourcegenGeneratedMarker = "Code generated by sourcegen; DO NOT EDIT."

func isSourcegenGeneratedFile(path string) (bool, error) {
	body, err := os.ReadFile(path)
	if err != nil {
		return false, err
	}
	return isSourcegenGeneratedBody(body), nil
}

func isSourcegenGeneratedBody(body []byte) bool {
	return strings.Contains(string(body), sourcegenGeneratedMarker)
}
